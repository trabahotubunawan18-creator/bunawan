-- =====================================================================
--  Trabaho Tu Bunawan - PostgreSQL schema for Supabase
--  Converted from the XAMPP / MariaDB dump (trabaho_tu_bunawan.sql).
--
--  HOW TO RUN: Supabase dashboard -> SQL Editor -> New query -> paste this
--  whole file -> Run. Then run data.sql the same way (only if you want to
--  bring over your existing records).
--
--  Notes on the conversion (nothing here changes how the website behaves):
--   * Columns that were TINYINT(1) stay as 0/1 numbers (smallint), so the
--     PHP code that checks "is_active = 1" keeps working unchanged.
--   * ENUM columns became text with a CHECK that allows the same values.
--   * The one SET column (seeker_profiles.availability) is plain text that
--     holds a comma list such as 'part_time,weekends', exactly as before.
--   * MySQL compared text without caring about upper/lower case. Emails and
--     the unique names use citext so "Admin@x.com" still equals "admin@x.com".
--   * "ON UPDATE CURRENT_TIMESTAMP" became a small trigger on the 4 tables
--     that have an updated_at column.
--   * All dates/times are stored as Philippine time (Asia/Manila), the same
--     as your XAMPP setup showed them.
--   * The unused FULLTEXT index on job_posts was left out (no code uses it).
--   * Row Level Security is switched ON for every table with no policies.
--     The PHP site connects with the database login, which is not affected,
--     but nobody can read or change your tables through Supabase's public
--     API / anon key. Do not remove this.
-- =====================================================================

