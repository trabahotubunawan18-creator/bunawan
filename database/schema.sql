-- Sets updated_at whenever a row really changes (replaces MySQL's ON UPDATE CURRENT_TIMESTAMP)
create or replace function public.tbb_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if row(new.*) is distinct from row(old.*) then
    new.updated_at := timezone('Asia/Manila', now());
  end if;
  return new;
end;
$$;

